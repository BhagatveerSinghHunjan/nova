import type { ReactNode } from "react";
import Link from "next/link";
import { ExperimentStatus } from "@prisma/client";

import type { ExperimentView } from "@/lib/experiments/queries";
import { StatusPipeline } from "@/components/experiments/status-badge";
import { ObservationsPanel } from "@/components/experiments/observations-panel";
import { AnalysisPanel } from "@/components/experiments/analysis-panel";
import { FindingPanel } from "@/components/experiments/finding-panel";
import { ProvenancePanel } from "@/components/experiments/provenance-panel";
import { ActivityTimeline } from "@/components/experiments/activity-timeline";
import { LabEmpty, LabField, LabPanel } from "@/components/experiments/lab-ui";
import {
  ApprovalPanel,
  ApprovedActions,
  CompletedActions,
  DraftActions,
  FindingForm,
  RunningActions,
} from "@/components/experiments/lifecycle-actions";

function Section({
  step,
  eyebrow,
  title,
  children,
}: {
  step: string;
  eyebrow: string;
  title: string;
  children: ReactNode;
}) {
  return (
    <section className="scroll-mt-8 border-t border-zinc-800/90 pt-12 first:border-t-0 first:pt-0">
      <div className="mb-5 flex items-baseline gap-3">
        <span className="font-mono text-[10px] uppercase tracking-[0.22em] text-zinc-600">
          {step}
        </span>
        <div>
          <p className="font-mono text-[11px] uppercase tracking-[0.22em] text-zinc-500">
            {eyebrow}
          </p>
          <h2 className="mt-1 text-xl font-semibold tracking-tight text-zinc-50 sm:text-2xl">
            {title}
          </h2>
        </div>
      </div>
      <div>{children}</div>
    </section>
  );
}

function formatDate(value: Date | null | undefined) {
  if (!value) {
    return "—";
  }

  return new Intl.DateTimeFormat("en", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(value);
}

function formatFactorsSummary(
  factors: ExperimentView["experiment"]["factors"],
  factorLevels: ExperimentView["factorLevels"],
  units: ExperimentView["units"],
) {
  return factors
    .map((factor) => {
      const levels = factorLevels[factor] ?? [];
      const unit = units[factor] ?? "";
      return `${factor}: [${levels.join(", ")}] ${unit}`.trim();
    })
    .join("\n");
}

export function ExperimentLabView({ view }: { view: ExperimentView }) {
  const {
    experiment,
    factorLevels,
    units,
    estimatedObservations,
    observationCount,
    analysis,
    finding,
    replication,
  } = view;

  const factorsSummary = formatFactorsSummary(
    experiment.factors,
    factorLevels,
    units,
  );

  return (
    <div className="mx-auto flex w-full max-w-3xl flex-1 flex-col px-5 py-8 sm:px-6 sm:py-12">
      <div className="mb-10 space-y-2">
        <Link
          href="/experiments"
          className="font-mono text-[11px] uppercase tracking-[0.2em] text-zinc-500 transition hover:text-zinc-300"
        >
          ← Experiments
        </Link>
        <p className="font-mono text-xs uppercase tracking-[0.32em] text-zinc-300">
          NOVA LAB
        </p>
        <p className="font-mono text-[11px] uppercase tracking-[0.2em] text-zinc-600">
          Executable scientific environment
        </p>
      </div>

      <header className="space-y-4 border-b border-zinc-800/80 pb-10">
        <h1 className="max-w-3xl text-3xl font-semibold leading-tight tracking-tight text-zinc-50 sm:text-4xl sm:leading-tight">
          {experiment.question}
        </h1>
        <p className="max-w-2xl text-base leading-relaxed text-zinc-400 sm:text-lg">
          {experiment.hypothesis}
        </p>
        <p className="max-w-2xl text-xs leading-relaxed text-zinc-600">
          Synthetic experimental data generated by a deterministic simulation
          with stochastic noise.
        </p>
      </header>

      <div className="mt-4 flex flex-col gap-12 sm:gap-14">
        <Section step="01" eyebrow="Design" title="Experimental design">
          <LabPanel>
            <dl className="grid gap-5 sm:grid-cols-2">
              <div className="sm:col-span-2">
                <LabField label="Factors, levels, units">
                  <span className="whitespace-pre-wrap">
                    {factorsSummary || "No factors configured."}
                  </span>
                </LabField>
              </div>
              <LabField label="Replicates">{experiment.replicates}</LabField>
              <LabField label="Estimated observations">
                {estimatedObservations}
              </LabField>
              <LabField label="Seed" mono>
                {experiment.seed}
              </LabField>
              <LabField label="Simulation version" mono>
                {experiment.simulationVersion}
              </LabField>
              <LabField label="Created">
                {formatDate(experiment.createdAt)}
              </LabField>
              <LabField label="Updated">
                {formatDate(experiment.updatedAt)}
              </LabField>
            </dl>
          </LabPanel>
        </Section>

        <Section
          step="02"
          eyebrow="Current state"
          title={experiment.status.replaceAll("_", " ")}
        >
          <LabPanel
            tone={
              experiment.status === ExperimentStatus.AWAITING_APPROVAL
                ? "attention"
                : experiment.status === ExperimentStatus.REJECTED
                  ? "attention"
                  : "default"
            }
          >
            <StatusPipeline status={experiment.status} />
            {experiment.status === ExperimentStatus.REJECTED &&
            experiment.rejectionRationale ? (
              <p className="mt-5 text-sm text-zinc-300">
                <span className="font-mono text-[10px] uppercase tracking-[0.16em] text-zinc-500">
                  Rejection rationale
                </span>
                <span className="mt-2 block text-zinc-200">
                  {experiment.rejectionRationale}
                </span>
              </p>
            ) : null}
            {experiment.status === ExperimentStatus.APPROVED &&
            experiment.approvalRationale ? (
              <p className="mt-5 text-sm text-zinc-300">
                <span className="font-mono text-[10px] uppercase tracking-[0.16em] text-zinc-500">
                  Approval rationale
                </span>
                <span className="mt-2 block text-zinc-200">
                  {experiment.approvalRationale}
                </span>
              </p>
            ) : null}
          </LabPanel>
        </Section>

        <Section step="03" eyebrow="Action" title="Human approval / controls">
          <LabPanel tone="action">
            {experiment.status === ExperimentStatus.DRAFT && (
              <DraftActions experimentId={experiment.id} />
            )}
            {experiment.status === ExperimentStatus.AWAITING_APPROVAL && (
              <ApprovalPanel
                experimentId={experiment.id}
                question={experiment.question}
                hypothesis={experiment.hypothesis}
                factorsSummary={factorsSummary}
                replicates={experiment.replicates}
                estimatedObservations={estimatedObservations}
              />
            )}
            {experiment.status === ExperimentStatus.REJECTED && (
              <LabEmpty
                title="Rejected"
                message="This experiment cannot run until revised through the domain layer."
              />
            )}
            {experiment.status === ExperimentStatus.APPROVED && (
              <ApprovedActions experimentId={experiment.id} />
            )}
            {experiment.status === ExperimentStatus.RUNNING && (
              <RunningActions experimentId={experiment.id} />
            )}
            {experiment.status === ExperimentStatus.COMPLETED && (
              <CompletedActions experimentId={experiment.id} />
            )}
            {experiment.status === ExperimentStatus.ANALYZED && (
              <LabEmpty
                title="Analyzed"
                message="Review results and analysis below. Replication can be recorded through domain services."
              />
            )}
            {experiment.status === ExperimentStatus.REPLICATED && (
              <LabEmpty
                title="Replicated"
                message="Replication recorded. See replication and provenance below."
              />
            )}
          </LabPanel>
        </Section>

        <Section step="04" eyebrow="Results" title="Observations">
          <ObservationsPanel
            observations={experiment.observations}
            estimatedObservations={estimatedObservations}
          />
        </Section>

        <Section step="05" eyebrow="Analysis" title="Statistical analysis">
          <AnalysisPanel analysis={analysis} />
        </Section>

        <Section step="06" eyebrow="Finding" title="Recorded finding">
          <FindingPanel
            finding={finding}
            analysis={analysis}
            experimentId={experiment.id}
            findingForm={
              analysis ? (
                <FindingForm
                  experimentId={experiment.id}
                  analysisId={analysis.id}
                />
              ) : null
            }
          />
        </Section>

        <Section step="07" eyebrow="Replication" title="Replication result">
          {!replication ? (
            <LabEmpty
              title="No replication"
              message="No replication record persisted for this experiment."
            />
          ) : (
            <LabPanel>
              <dl className="grid gap-5 text-sm sm:grid-cols-2">
                <LabField label="Seeds" mono>
                  {replication.originalSeed} → {replication.replicationSeed}
                </LabField>
                <LabField label="Success" mono>
                  {replication.replicationSuccess ? "true" : "false"}
                </LabField>
                <LabField label="Criteria">
                  <span className="block font-mono text-xs leading-relaxed text-zinc-400">
                    same direction: {String(replication.sameDirection)}
                    <br />
                    CI overlap: {String(replication.confidenceIntervalOverlap)}
                    <br />
                    relative diff: {replication.relativeEffectDifference}
                  </span>
                </LabField>
                <LabField label="Replica experiment">
                  <Link
                    href={`/experiments/${replication.replicationExperimentId}`}
                    className="text-zinc-100 underline-offset-2 hover:underline"
                  >
                    {replication.replicationExperiment.question}
                  </Link>
                </LabField>
              </dl>
            </LabPanel>
          )}
        </Section>

        <Section step="08" eyebrow="Provenance" title="Traceability">
          <LabPanel tone="muted">
            <ProvenancePanel
              experiment={{
                id: experiment.id,
                question: experiment.question,
                factors: experiment.factors,
                replicates: experiment.replicates,
                seed: experiment.seed,
                simulationVersion: experiment.simulationVersion,
                createdAt: experiment.createdAt,
                updatedAt: experiment.updatedAt,
                observationCount,
                parentExperiment: experiment.parentExperiment,
                childExperiments: experiment.childExperiments,
              }}
              factorLevels={factorLevels}
              analysis={analysis}
              finding={finding}
              replication={replication}
            />
          </LabPanel>
        </Section>

        <Section step="09" eyebrow="History" title="Event history">
          <div className="mb-5">
            <Link
              href={`/activity?experimentId=${experiment.id}`}
              className="font-mono text-[11px] uppercase tracking-[0.16em] text-zinc-500 underline-offset-2 hover:text-zinc-300 hover:underline"
            >
              Open in activity view
            </Link>
          </div>
          <LabPanel tone="muted">
            <ActivityTimeline events={experiment.events} />
          </LabPanel>
        </Section>
      </div>
    </div>
  );
}
