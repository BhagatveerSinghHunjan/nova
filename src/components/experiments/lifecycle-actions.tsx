export function FindingForm({
  experimentId,
  analysisId,
}: {
  experimentId: string;
  analysisId: string;
}) {
  const [pending, startTransition] = useTransition();
  const [text, setText] = useState("");
  const [confidence, setConfidence] = useState("0.8");
  const [result, setResult] = useState<ActionResult | null>(null);

  return (
    <div className="space-y-4 border border-zinc-800 bg-zinc-950/30 p-4">
      <p className="text-sm text-zinc-400">
        Record a finding linked to the persisted analysis.
      </p>
      <textarea
        value={text}
        onChange={(event) => setText(event.target.value)}
        rows={3}
        className="w-full border border-zinc-700 bg-zinc-950 px-3 py-2.5 text-sm text-zinc-100 outline-none focus:border-zinc-400"
        placeholder="Finding text"
      />
      <input
        type="number"
        min={0}
        max={1}
        step={0.01}
        value={confidence}
        onChange={(event) => setConfidence(event.target.value)}
        className="w-36 border border-zinc-700 bg-zinc-950 px-3 py-2.5 text-sm text-zinc-100 outline-none focus:border-zinc-400"
        aria-label="Confidence"
      />
      <div>
        <button
          type="button"
          disabled={pending || !text.trim()}
          onClick={() => {
            startTransition(async () => {
              setResult(
                await saveFindingAction({
                  experimentId,
                  analysisId,
                  findingText: text,
                  confidence: Number(confidence),
                }),
              );
            });
          }}
          className={labButtonClass("primary", pending)}
        >
          {pending ? "Saving…" : "Save finding"}
        </button>
      </div>
      <PendingHint pending={pending} label="Persisting finding…" />
      <ActionMessage result={result} />
    </div>
  );
}
