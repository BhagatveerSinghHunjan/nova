"use client";

import { useState, useTransition } from "react";

import type { ActionResult } from "@/app/experiments/actions";
import {
  analyzeExperimentAction,
  approveExperimentAction,
  completeExperimentAction,
  rejectExperimentAction,
  saveFindingAction,
  startExperimentAction,
  submitForApprovalAction,
} from "@/app/experiments/actions";
import { LabError, LabField, labButtonClass } from "@/components/experiments/lab-ui";

function ActionMessage({ result }: { result: ActionResult | null }) {
  if (!result || result.ok) {
    return null;
  }

  return <LabError message={result.error ?? "Action failed"} />;
}

function PendingHint({ pending, label }: { pending: boolean; label: string }) {
  if (!pending) {
    return null;
  }

  return (
    <p className="mt-3 font-mono text-[11px] uppercase tracking-[0.16em] text-zinc-500">
      {label}
    </p>
  );
}

export function DraftActions({ experimentId }: { experimentId: string }) {
  const [pending, startTransition] = useTransition();
  const [result, setResult] = useState<ActionResult | null>(null);

  return (
    <div>
      <p className="mb-5 max-w-xl text-sm leading-relaxed text-zinc-400">
        This experiment is a draft. Submit it for human approval before it can
        run.
      </p>
      <button
        type="button"
        disabled={pending}
        onClick={() => {
          startTransition(async () => {
            setResult(await submitForApprovalAction(experimentId));
          });
        }}
        className={labButtonClass("primary", pending)}
      >
        {pending ? "Submitting…" : "Submit for approval"}
      </button>
      <PendingHint pending={pending} label="Updating experiment state…" />
      <ActionMessage result={result} />
    </div>
  );
}

export function ApprovalPanel({
  experimentId,
  question,
  hypothesis,
  factorsSummary,
  replicates,
  estimatedObservations,
}: {
  experimentId: string;
  question: string;
  hypothesis: string;
  factorsSummary: string;
  replicates: number;
  estimatedObservations: number;
}) {
  const [pending, startTransition] = useTransition();
  const [rejectionReason, setRejectionReason] = useState("");
  const [result, setResult] = useState<ActionResult | null>(null);

  return (
    <div className="space-y-6">
      <div>
        <p className="font-mono text-[11px] uppercase tracking-[0.2em] text-amber-300/90">
          Human approval required
        </p>
        <p className="mt-2 max-w-xl text-sm leading-relaxed text-zinc-400">
          Review the design. Approval is enforced by the server. Rejected
          experiments cannot run.
        </p>
      </div>

      <dl className="grid gap-4 sm:grid-cols-2">
        <LabField label="Question">{question}</LabField>
        <LabField label="Hypothesis">{hypothesis}</LabField>
        <LabField label="Factors / levels">
          <span className="whitespace-pre-wrap">{factorsSummary}</span>
        </LabField>
        <LabField label="Replicates / observations">
          {replicates} replicates · ~{estimatedObservations} observations
        </LabField>
      </dl>

      <p className="border border-zinc-800 bg-zinc-950/60 px-3 py-2.5 text-xs leading-relaxed text-zinc-500">
        Synthetic experimental data generated by a deterministic simulation with
        stochastic noise.
      </p>

      <div className="space-y-2">
        <label
          htmlFor="rejection-reason"
          className="block font-mono text-[10px] uppercase tracking-[0.18em] text-zinc-500"
        >
          Rejection reason
        </label>
        <textarea
          id="rejection-reason"
          value={rejectionReason}
          onChange={(event) => setRejectionReason(event.target.value)}
          rows={3}
          className="w-full border border-zinc-700 bg-zinc-950 px-3 py-2.5 text-sm text-zinc-100 outline-none focus:border-zinc-400"
          placeholder="Required when rejecting"
        />
      </div>

      <div className="flex flex-wrap gap-3">
        <button
          type="button"
          disabled={pending}
          onClick={() => {
            startTransition(async () => {
              setResult(
                await approveExperimentAction(
                  experimentId,
                  "Human approval granted via NOVA LAB UI.",
                ),
              );
            });
          }}
          className={labButtonClass("approve", pending)}
        >
          {pending ? "Working…" : "Approve"}
        </button>
        <button
          type="button"
          disabled={pending || !rejectionReason.trim()}
          onClick={() => {
            startTransition(async () => {
              setResult(
                await rejectExperimentAction(experimentId, rejectionReason),
              );
            });
          }}
          className={labButtonClass("reject", pending)}
        >
          {pending ? "Working…" : "Reject"}
        </button>
      </div>
      <PendingHint pending={pending} label="Persisting approval decision…" />
      <ActionMessage result={result} />
    </div>
  );
}

